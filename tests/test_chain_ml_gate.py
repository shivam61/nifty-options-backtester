"""ML gate hooks of the real-price chain backtest: ChainConfig.entry_gate and ChainConfig.exit_gate.

Both hooks default to None. With no gate the engine output must be unchanged. Gates are plain
callables injected by the caller; this module loads no model. Synthetic archive only (no network,
no real NSE archive): the IC cycle comes from tests/test_chain_engine.py.
"""

import json
from datetime import date

import pandas as pd
import pytest

from backtester.chain_engine import ML_EXIT_REASON, SKIP_REASONS, ChainBacktest, ChainConfig
from data.nse_fo_archive import NseFoArchive
from strategies.base import Trade
from strategies.weekly_strategies import WeeklyExitArms
from tests.test_chain_engine import E, F, S, SPOT, _market, _row, _write, _write_ic_world

D6, D7 = date(2025, 1, 6), date(2025, 1, 7)
# IC legs generated by WeeklyIronCondor at SPOT, VIX 15, DTE 6 (asserted in _write_ic_world)
STRIKES = [(23350, "CE"), (23600, "CE"), (22450, "PE"), (22200, "PE")]  # short CE, long CE, short PE, long PE
FILL_DEFAULT = (30.0, 10.0, 25.0, 8.0)  # settles at F, D6, D7 (default IC world)
EXPECTED_CTX_KEYS = {
    "date", "trade", "strategy", "fill_date", "dte", "holding_sessions", "holding_days",
    "entry_spot", "spot", "entry_vix", "vix", "entry_credit_rs", "mark_pnl_rs",
    "mark_pnl_pct_credit", "peak_pnl_rs", "short_strikes", "short_dist_pct", "rule_exit",
}


def _ic_world(root, d6_settles=None, spot_map=None, with_expiry=False):
    """IC cycle S, F, D6, D7, X (DTE 1). Optional D6 settle override; optional expiry-day rows (E).

    With with_expiry the calendar gets E appended, and E rows settle at index 23000 (all four
    strikes expire worthless), so a trade that is held to expiry closes on E.
    """
    days = _write_ic_world(root)
    if d6_settles is not None:
        _write(root, D6, [_row(D6, E, k, o, v) for (k, o), v in zip(STRIKES, d6_settles)])
    if with_expiry:
        _write(root, E, [_row(E, E, k, o, 23000.0, close=0.0) for k, o in STRIKES])
        days = days + [E]
    return days, _market(days, vix=15.0, spot_map=spot_map)


def _run(root, days, mk, **cfg_extra):
    arch = NseFoArchive(archive_dir=str(root))
    bt = ChainBacktest(arch, mk, ChainConfig(start=S, end=S, **cfg_extra))
    return bt, bt.run()


def _dump(trades):
    return json.dumps(trades, sort_keys=True, default=str)


# ----------------------------------------------------------------- defaults / no-op
def test_gates_default_to_none_and_reason_is_registered():
    cfg = ChainConfig()
    assert cfg.entry_gate is None and cfg.exit_gate is None
    assert "ml_gate" in SKIP_REASONS
    assert ML_EXIT_REASON == "ml_exit"


def test_gates_none_gives_same_trades_and_no_new_keys(tmp_path):
    days, mk = _ic_world(tmp_path)
    bt0, t0 = _run(tmp_path, days, mk)
    bt1, t1 = _run(tmp_path, days, mk, entry_gate=None, exit_gate=None)
    assert len(t0) == 1
    assert _dump(t0) == _dump(t1)
    assert t0[0]["exit_reason"] == "dte_limit"           # rule exit on X, as before the hooks
    assert "entry_gate_score" not in t0[0] and "exit_gate_score" not in t0[0]
    assert bt0.skips == bt1.skips and bt0.skip_log == bt1.skip_log
    assert "ml_gate" not in bt1.skips


def test_gates_none_never_builds_exit_context(tmp_path, monkeypatch):
    """With exit_gate None the context builder is never reached (the hook is a no-op)."""
    def _boom(self, *a, **k):
        raise AssertionError("exit context built with no exit_gate configured")
    monkeypatch.setattr(ChainBacktest, "_gate_ctx", _boom)
    days, mk = _ic_world(tmp_path)
    _, trades = _run(tmp_path, days, mk)
    assert len(trades) == 1 and trades[0]["exit_reason"] == "dte_limit"


# ----------------------------------------------------------------- entry gate
def test_entry_gate_false_skips_under_ml_gate(tmp_path):
    days, mk = _ic_world(tmp_path)
    bt, trades = _run(tmp_path, days, mk, entry_gate=lambda d, name, vix, row: (False, 0.12))
    assert trades == []
    assert bt.skips["ml_gate"] == 1
    assert bt.skip_log == [{
        "date": str(S), "reason": "ml_gate", "strategy": "weekly_ic", "vix": 15.0,
        "entry_gate_score": 0.12, "entry_gate_allow": False,
    }]
    # skip log still serialises to CSV with the runner's DataFrame path
    csv = pd.DataFrame(bt.skip_log).to_csv(index=False)
    assert "ml_gate" in csv and "entry_gate_score" in csv


def test_entry_gate_true_trade_equals_baseline_plus_score(tmp_path):
    days, mk = _ic_world(tmp_path)
    _, base = _run(tmp_path, days, mk)
    seen = []

    def gate(d, name, vix, row):
        seen.append((d, name, vix, dict(row)))
        return True, 0.73

    bt, trades = _run(tmp_path, days, mk, entry_gate=gate)
    assert len(trades) == 1 and "ml_gate" not in bt.skips
    got = dict(trades[0])
    assert got.pop("entry_gate_score") == 0.73
    assert got == base[0]
    assert "exit_gate_score" not in trades[0]
    assert seen == [(S, "weekly_ic", 15.0, {"nifty_return_5d": 0.0, "vix_change_5d": 0.0})]


def test_entry_gate_score_is_coerced_to_float(tmp_path):
    import numpy as np
    days, mk = _ic_world(tmp_path)
    _, trades = _run(tmp_path, days, mk, entry_gate=lambda d, n, v, r: (np.bool_(True), np.float32(0.5)))
    assert isinstance(trades[0]["entry_gate_score"], float) and trades[0]["entry_gate_score"] == 0.5


# ----------------------------------------------------------------- exit gate
def test_exit_gate_fires_on_dte_positive_day_at_that_days_mark(tmp_path):
    days, mk = _ic_world(tmp_path)
    calls = []

    def exit_gate(ctx):
        calls.append(ctx["date"])
        return ctx["date"] == D6, float(ctx["dte"])

    _, trades = _run(tmp_path, days, mk, exit_gate=exit_gate)
    assert len(trades) == 1
    t = trades[0]
    assert calls == [D6]                                  # closed on D6, so D7 and X are never reached
    assert t["exit_date"] == str(D6) and t["exit_reason"] == ML_EXIT_REASON
    assert t["dte_at_exit"] == 3 and t["holding_sessions"] == 1
    assert t["exit_gate_score"] == 3.0
    assert "entry_gate_score" not in t
    # exit settle is the D6 settle of each leg (default D6 marks = fills)
    assert {(l["type"], l["strike"]): l["exit_settle"] for l in t["legs"]} == {
        (o, k): v for (k, o), v in zip(STRIKES, FILL_DEFAULT)}


def test_exit_gate_never_called_when_dte_is_zero(tmp_path):
    days, mk = _ic_world(tmp_path, with_expiry=True)
    calls = []

    def exit_gate(ctx):
        calls.append(ctx["dte"])
        return False, 0.0

    _, trades = _run(tmp_path, days, mk, exit_gate=exit_gate,
                     exit_arms=WeeklyExitArms(hold_to_expiry=True))
    assert len(trades) == 1
    assert trades[0]["exit_date"] == str(E) and trades[0]["exit_reason"] == "expiry"
    assert calls == [3, 2, 1]                             # D6, D7, X; expiry day E (dte 0) not called
    assert trades[0]["exit_gate_score"] == 0.0            # last evaluated score (X, dte 1), not E


def test_exit_gate_does_not_override_rule_exit(tmp_path):
    """Breach on D6 fires the rules; an always-True gate must not relabel that exit as ml_exit."""
    days, mk = _ic_world(tmp_path, spot_map={D6: 23400.0, D7: 23400.0})
    _, base = _run(tmp_path, days, mk)
    seen_rule = []

    def exit_gate(ctx):
        seen_rule.append((ctx["date"], ctx["rule_exit"]))
        return True, 1.0

    _, trades = _run(tmp_path, days, mk, exit_gate=exit_gate)
    assert len(trades) == 1
    assert trades[0]["exit_reason"] == base[0]["exit_reason"] != ML_EXIT_REASON
    assert trades[0]["exit_date"] == base[0]["exit_date"]
    assert seen_rule[0] == (date.fromisoformat(base[0]["exit_date"]), True)  # gate saw rule_exit=True


def test_exit_gate_context_keys_and_values(tmp_path):
    days, mk = _ic_world(tmp_path, d6_settles=(35.0, 10.0, 25.0, 8.0))
    seen = {}

    def exit_gate(ctx):
        if ctx["date"] == D6:
            seen.update(ctx)
        return False, 0.0

    _run(tmp_path, days, mk, exit_gate=exit_gate)
    assert set(seen) == EXPECTED_CTX_KEYS
    assert isinstance(seen["trade"], Trade)
    assert seen["strategy"] == "weekly_ic" and seen["fill_date"] == F
    assert seen["dte"] == 3 and seen["holding_sessions"] == 1 and seen["holding_days"] == (D6 - F).days
    assert seen["entry_spot"] == pytest.approx(SPOT) and seen["spot"] == pytest.approx(SPOT)
    assert seen["entry_vix"] == 15.0 and seen["vix"] == 15.0
    assert seen["rule_exit"] is False
    # entry fills: short 30 -> 29.55, long 10 -> 10.45, short 25 -> 24.55, long 8 -> 8.45 (credit 35.20/unit)
    assert seen["entry_credit_rs"] == pytest.approx(35.20 * 65)
    # D6 marks 35/10/25/8 vs fills: legs' P&L at marks, before exit costs
    expect_pnl = (29.55 - 35) * 65 + (10 - 10.45) * 65 + (24.55 - 25) * 65 + (8 - 8.45) * 65
    assert seen["mark_pnl_rs"] == pytest.approx(expect_pnl)  # -442.0
    assert seen["mark_pnl_pct_credit"] == pytest.approx(expect_pnl / (35.20 * 65))
    assert seen["peak_pnl_rs"] == 0.0                     # tracker floors peak at 0 (never above fill)
    assert sorted(seen["short_strikes"]) == [("CE", 23350), ("PE", 22450)]
    assert seen["short_dist_pct"] == pytest.approx(min(23350 - SPOT, SPOT - 22450) / SPOT)
